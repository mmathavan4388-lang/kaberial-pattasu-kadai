export class Lines {
  constructor() {
    this.last = {};
  }
  pick(cat) {
    const list = LINES[cat] || LINES.greet;
    let i = Math.floor(Math.random() * list.length);
    if (list.length > 1 && i === this.last[cat]) i = (i + 1) % list.length;
    this.last[cat] = i;
    return list[i];
  }
  /** Contextual greeting for a role at a given hour. */
  forRole(role, hour) {
    const map = {
      shop_owner: 'shop_owner', tea_master: 'tea_master', police: 'police', student: 'student', boy: 'student', girl: 'student',
      oldman: 'old', oldwoman: 'old', factory_worker: 'factory_worker', vendor: 'vendor', priest: 'priest',
      doctor: 'doctor', nurse: 'doctor', driver: 'driver', firefighter: 'firefighter', teacher: 'student',
    };
    if (map[role] && Math.random() < 0.75) return this.pick(map[role]);
    if (hour < 10 && Math.random() < 0.5) return this.pick('morning');
    if ((hour >= 21 || hour < 5) && Math.random() < 0.6) return this.pick('night');
    return this.pick('greet');
  }
}
